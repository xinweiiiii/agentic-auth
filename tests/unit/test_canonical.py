"""RFC 8785 canonicalization and the binding hash.

Every vector in ``tests/fixtures/jcs_vectors.json`` was typed from the RFC or the contract
by hand, never generated by the code under test.
"""

from __future__ import annotations

import hashlib
import json
import math
from pathlib import Path

import pytest

from agentic_auth.verify.canonical import (
    CanonicalizationError,
    binding_document,
    binding_hash,
    canonical_json,
    select_binding,
)

VECTORS = json.loads(
    (Path(__file__).resolve().parents[1] / "fixtures" / "jcs_vectors.json").read_text()
)

_SPECIAL = {"NaN": math.nan, "Infinity": math.inf, "-Infinity": -math.inf}


@pytest.mark.parametrize(
    "vector", [v for v in VECTORS["vectors"] if not v.get("error")], ids=lambda v: v["name"]
)
def test_vector_canonicalizes_to_the_documented_string(vector) -> None:
    assert canonical_json(vector["input"]).decode("utf-8") == vector["canonical"]


@pytest.mark.parametrize(
    "vector", [v for v in VECTORS["vectors"] if v.get("error")], ids=lambda v: v["name"]
)
def test_non_json_numbers_are_rejected(vector) -> None:
    with pytest.raises(CanonicalizationError):
        canonical_json({"a": _SPECIAL[vector["input_repr"]]})


def test_equivalent_numeric_forms_hash_identically() -> None:
    forms = [{"a": 1}, {"a": 1.0}, {"a": 1e0}, {"a": 100e-2}, {"a": 0.1e1}]
    assert len({canonical_json(f) for f in forms}) == 1


def test_five_serializations_of_one_object_agree() -> None:
    """Key order, whitespace and numeric form never change the binding."""
    texts = [
        '{"account_id":"acc-42","notify":true,"reason":"fraud","amount":10}',
        '{ "reason": "fraud", "account_id": "acc-42", "amount": 10.0, "notify": true }',
        '{"notify":true,\n  "amount":1e1,\n  "account_id":"acc-42",\n  "reason":"fraud"}',
        '{"amount":10,"reason":"fraud","notify":true,"account_id":"acc-42"}',
        '{"account_id": "acc-42", "amount": 1E1, "notify": true, "reason": "fraud"}',
    ]
    hashes = {
        binding_hash("mcp://accounts.internal/terminate_account", json.loads(t), None)
        for t in texts
    }
    assert len(hashes) == 1


def test_depth_is_capped() -> None:
    nested: dict = {}
    node = nested
    for _ in range(70):
        node["x"] = {}
        node = node["x"]
    with pytest.raises(CanonicalizationError, match="deeper"):
        canonical_json(nested)


def test_non_json_values_are_rejected() -> None:
    with pytest.raises(CanonicalizationError):
        canonical_json({"a": {1, 2}})
    with pytest.raises(CanonicalizationError):
        canonical_json({"a": b"bytes"})


def test_key_order_is_utf16_code_units_not_code_points() -> None:
    """A supplementary-plane character sorts BEFORE U+FF5E in UTF-16, after it by code point."""
    doc = {"\U0001d11e": 1, "～": 2}
    assert canonical_json(doc).decode() == '{"\U0001d11e":1,"～":2}'


# -- binding selection ---------------------------------------------------------------


def test_whole_body_binds_when_no_pointers_are_declared() -> None:
    params = {"b": 1, "a": {"c": 2}}
    assert select_binding(params, None) == params


def test_pointers_select_resolving_paths_and_omit_missing_ones() -> None:
    params = {"account_id": "acc-42", "nested": {"list": [10, 20]}, "a/b": 1, "t~": 2}
    binding = ["/account_id", "/nested/list/1", "/missing", "/a~1b", "/t~0", "/nested/list/9"]
    assert select_binding(params, binding) == {
        "/account_id": "acc-42",
        "/nested/list/1": 20,
        "/a~1b": 1,
        "/t~0": 2,
    }


def test_a_missing_binding_parameter_changes_the_hash() -> None:
    target = "mcp://accounts.internal/terminate_account"
    with_it = binding_hash(target, {"account_id": "acc-42", "reason": "x"}, ["/account_id"])
    without = binding_hash(target, {"reason": "x"}, ["/account_id"])
    assert with_it != without


def test_non_binding_parameters_may_vary() -> None:
    target = "mcp://accounts.internal/terminate_account"
    a = binding_hash(target, {"account_id": "acc-42", "reason": "fraud"}, ["/account_id"])
    b = binding_hash(target, {"account_id": "acc-42", "reason": "closed"}, ["/account_id"])
    assert a == b


def test_the_contract_binding_vector() -> None:
    v = VECTORS["binding_vector"]
    doc = binding_document(v["target"], v["params"], v["binding"])
    assert canonical_json(doc).decode() == v["document_canonical"]
    whole = binding_document(v["target"], v["params"], None)
    assert canonical_json(whole).decode() == v["whole_body_canonical"]
    expected = hashlib.sha256(v["document_canonical"].encode()).digest()
    import base64

    assert (
        binding_hash(v["target"], v["params"], v["binding"])
        == base64.urlsafe_b64encode(expected).rstrip(b"=").decode()
    )


def test_the_target_is_part_of_the_binding() -> None:
    params = {"account_id": "acc-42"}
    assert binding_hash("mcp://a/read", params, None) != binding_hash(
        "mcp://a/terminate", params, None
    )
